"""
Merlin-specific analysis of the .flow recordings (works without mitmproxy installed).
Merlin uses plain JSON over HTTPS to www.getmerlin.in/arcane/api/v2/extension/: chat (prompt, tab list), chat/completions
(context summary incl. page content), sync-session (turn saved on the server), telemetry.
Per run: hosts, prompts with their tab list, page content uploaded, models named, where each marker appeared.
Usage: python merlin_report.py <evidence/merlin> <markers.csv> <out.md>
"""
import csv, json, os, re, sys
from collections import Counter, defaultdict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tnetstring_reader import flows

FIRST = ("getmerlin.in", "foyer.work")
def s(x): return x.decode("utf-8", "replace") if isinstance(x, bytes) else (x or "")
def party(h):
    if h.startswith("127.0.0.1") or h == "soen321.test": return "local"
    if any(h == d or h.endswith("." + d) for d in FIRST): return "Merlin"
    return "THIRD PARTY"

def text_of(content):
    if isinstance(content, str): return content
    if isinstance(content, list): return " ".join(c.get("text", "") for c in content if isinstance(c, dict))
    return ""

def tool_results(obj):
    """Yield (tool name or '', text) for every tool result anywhere in a request body (chat, completions, sync-session)."""
    if isinstance(obj, dict):
        if obj.get("role") == "tool":
            yield "", text_of(obj.get("content"))
        if "toolResults" in obj:
            for tr in obj["toolResults"]:
                yield (tr.get("function") or {}).get("name", ""), text_of(tr.get("content"))
            return
        for v in obj.values(): yield from tool_results(v)
    elif isinstance(obj, list):
        for v in obj: yield from tool_results(v)

def page_of(result_text):
    """read_content results are JSON {success, data:'Title: ...\\nURL: ...\\n---\\n<markdown>'}."""
    try: data = json.loads(result_text).get("data", "")
    except Exception: data = result_text
    if not isinstance(data, str): data = json.dumps(data)
    url = re.search(r"^URL: (.*)$", data, re.M)
    body = data.split("\n---\n", 1)[-1]
    if url: return url.group(1), body
    if body.lstrip().startswith('[{"title"'): return "(web search results)", body
    if "managedTabs" in body: return "(list_tabs result)", body
    return "(other tool result)", body

def run_report(path, markers):
    hosts = Counter(); hits = defaultdict(set); prompts = []; uploads = {}; models = Counter(); navs = []; tools = Counter()
    for f in flows(path):
        r = f["request"]; h = s(r["host"]); p = s(r.get("path")); body = s(r.get("content"))
        hosts[h] += 1
        blob = p + " " + body
        for label, val in markers:
            if val.lower() in blob.lower():
                ep = "/" + "/".join(p.split("?")[0].rstrip("/").split("/")[-2:]) if party(h) == "Merlin" else ""
                hits[label].add(f"{h}{ep} ({party(h)})")
        if party(h) != "Merlin" or not body.startswith("{"): continue
        try: d = json.loads(body)
        except Exception: continue
        if "model" in d and isinstance(d["model"], str): models[(p.rsplit("/", 2)[-2] + "/" + p.rsplit("/", 1)[-1], d["model"])] += 1
        if p.endswith("/extension/chat"):
            msgs = d.get("messages", [])
            user = [text_of(m.get("content")) for m in msgs if m.get("role") == "user"]
            tabs = [m["content"] for m in msgs if m.get("_tag") == "tab_context"]
            if user and not any(m.get("role") == "tool" for m in msgs[-1:]):
                prompts.append((user[-1], tabs[0] if tabs else ""))
        if p.endswith("extensionLogger"):
            navs.append(d.get("url", ""))
        for name, txt in tool_results(d):
            url, page = page_of(txt)
            tools[name or "tool"] += 1
            key = (url, page[:200])
            if key not in uploads: uploads[key] = (url, page, set())
            uploads[key][2].add(p.rsplit("/", 1)[-1])
    return hosts, hits, prompts, list(uploads.values()), models, navs, tools

def main(d, markers_csv, out):
    markers = [(r["label"], r["value"]) for r in csv.DictReader(open(markers_csv, encoding="utf-8-sig"))]
    L = ["# Merlin: analysis of recordings\n", "Generated by `analysis/merlin_report.py`. Auth links are redacted.\n"]
    # Experiment runs only: setup runs (E0) contain the test account's sign-in URLs.
    for name in sorted(n for n in os.listdir(d) if re.match(r"E[1-4]_run\d+\.flow$", n)):
        hosts, hits, prompts, uploads, models, navs, tools = run_report(os.path.join(d, name), markers)
        L.append(f"## {name}\n")
        tp = sorted(h for h in hosts if party(h) == "THIRD PARTY")
        L.append(f"- {sum(hosts.values())} requests to {len(hosts)} hosts")
        L.append(f"- third-party hosts (includes Edge's own background traffic): {', '.join(tp) if tp else 'none'}")
        L.append(f"- models named in requests: " + ", ".join(f"{m} via {ep} ({n}x)" for (ep, m), n in sorted(models.items())))
        if navs: L.append(f"- page navigations logged to extensionLogger: {len(navs)}: " + ", ".join(u.split("?")[0] for u in navs[:10]))
        L.append(f"\n**Prompts sent ({len(prompts)}), with the tab list attached to each:**\n")
        for u, tabs in prompts:
            tl = re.findall(r'title: "([^"]*)" \| url: (\S+)', tabs)
            L.append(f"- \"{u[:120]}\" | tabs: " + "; ".join(f"{t} <{url}>" for t, url in tl))
        L.append("\n**Markers found in traffic sent from the browser:**\n")
        for label, val in markers:
            if label in hits: L.append(f"- `{label}` ({val}) -> {', '.join(sorted(hits[label]))}")
        L.append(f"\n**Page content uploaded to Merlin ({len(uploads)} distinct tool results):**\n")
        for url, page, where in uploads:
            L.append(f"- {url}: {len(page)} chars, sent in {', '.join(sorted(where))}\n\n  > " + page[:1200].replace("\n", " ") + "\n")
        L.append("")
    text = redact("\n".join(L))
    open(out, "w", encoding="utf-8").write(text)
    print(text[:4000])

def redact(text):
    """Live third-party auth links (Merlin's agent started Slack/YouTube connections through Composio)."""
    return re.sub(r"https://connect\.composio\.dev/link/[\w-]+", "[redacted Composio auth link]", text)

if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if len(sys.argv) != 4: sys.exit(__doc__)
    main(*sys.argv[1:4])
